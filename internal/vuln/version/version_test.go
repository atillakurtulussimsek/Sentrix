package version

import "testing"

type tc struct {
	a, b string
	want int
}

func check(t *testing.T, name string, f func(a, b string) int, cases []tc) {
	t.Helper()
	for _, c := range cases {
		if got := f(c.a, c.b); got != c.want {
			t.Errorf("%s(%q, %q) = %d, want %d", name, c.a, c.b, got, c.want)
		}
		if got := f(c.b, c.a); got != -c.want {
			t.Errorf("%s(%q, %q) = %d, want %d (antisymmetry)", name, c.b, c.a, got, -c.want)
		}
	}
}

