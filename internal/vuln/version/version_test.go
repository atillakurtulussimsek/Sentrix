func TestCompareDispatch(t *testing.T) {
	if _, err := Compare("nope", "1", "2"); err == nil {
		t.Fatal("expected error")
	}
	if c, _ := Compare(Dpkg, "1.0~1", "1.0"); c != -1 {
		t.Fatal("dpkg dispatch")
	}
	if s, ok := SchemeForDistro("rocky"); !ok || s != RPM {
		t.Fatal("rocky scheme")
	}
}
